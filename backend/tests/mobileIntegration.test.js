import test from 'node:test';
import assert from 'node:assert/strict';
import { PrismaClient } from '@prisma/client';
import express from 'express';
import { createExecutionService, deletePlanWithExecutionGuard, reconcileExecutionMembers } from '../src/services/executionService.js';
import { refreshToken, createAuthResponse, logout } from '../src/services/authService.js';
import { getMessages, getTripGroupMessages } from '../src/services/chatService.js';
import authRoutes from '../src/routes/auth.js';
import locationRoutes from '../src/routes/locations.js';
import executionRoutes from '../src/routes/executions.js';
import itineraryRoutes from '../src/routes/itineraries.js';
import { errorHandler } from '../src/middleware/errorMiddleware.js';
import { weatherRouter } from '../src/routes/weather.js';

const isolated = process.env.MOBILE_TEST_DATABASE_URL && new URL(process.env.MOBILE_TEST_DATABASE_URL).pathname.startsWith('/plantravel_mobile_test_') && process.env.DATABASE_URL === process.env.MOBILE_TEST_DATABASE_URL;
test('Mobile API integration on a disposable migrated database', { skip: !isolated }, async t => {
    const db = new PrismaClient();
    t.after(() => db.$disconnect());
    const users = await Promise.all(['Owner', 'Member', 'Outsider'].map(name => db.users.create({ data: { full_name: name, email: `${name}@mobile.test`, role: 'user', is_active: true } })));
    const [owner, member, outsider] = users;
    const plan = await db.itineraries.create({ data: { user_id: owner.id, name: 'Original plan', status: 'draft',
        collaborators: { create: { user_id: member.id, permission: 'view' } },
        itinerary_items: { create: [{ custom_name: 'First', sort_order: 1, note: '[DAY:1] Morning' }, { custom_name: 'Second', sort_order: 2 }] } } });
    const service = createExecutionService(db);
    const [first, repeat] = await Promise.all([service.start(String(plan.id), String(owner.id)), service.start(String(plan.id), String(owner.id))]);
    assert.equal(first.id, repeat.id, 'duplicate starts create one execution');
    const second = await service.start(String(plan.id), String(member.id));
    assert.notEqual(first.id, second.id);
    await db.itinerary_items.deleteMany({ where: { itinerary_id: plan.id } });
    await db.itineraries.update({ where: { id: plan.id }, data: { name: 'Changed plan' } });
    assert.equal((await service.get(String(plan.id), String(owner.id))).snapshot.name, 'Original plan');
    assert.equal((await service.get(String(plan.id), String(owner.id))).stops.length, 2);
    await assert.rejects(service.start(String(plan.id), String(outsider.id)), error => error.status === 403);
    await assert.rejects(service.updateStop(first.id, first.stops[0].id, String(member.id), { status: 'arrived', version: 0 }), error => error.status === 404);
    const another = await db.itineraries.create({ data: { user_id: owner.id, name: 'Another', itinerary_items: { create: { custom_name: 'Other', sort_order: 1 } } } });
    await assert.rejects(service.start(String(another.id), String(owner.id)), error => error.code === 'ANOTHER_EXECUTION_ACTIVE');
    await assert.rejects(deletePlanWithExecutionGuard(db, String(plan.id), String(owner.id)), error => error.status === 409);

    const racePlan = await db.itineraries.create({ data: { user_id: outsider.id, name: 'Concurrency', itinerary_items: { create: [{ custom_name: 'A', sort_order: 1 }, { custom_name: 'B', sort_order: 2 }] } } });
    const race = await service.start(String(racePlan.id), String(outsider.id));
    const writes = await Promise.allSettled(race.stops.map(stop => service.updateStop(race.id, stop.id, String(outsider.id), { status: 'skipped', version: 0 })));
    assert.equal(writes.filter(write => write.status === 'fulfilled').length, 1);
    assert.equal(writes.find(write => write.status === 'rejected').reason.code, 'VERSION_CONFLICT');

    const arrived = await service.updateStop(first.id, first.stops[0].id, String(owner.id), { status: 'arrived', version: 0 });
    const duplicate = await service.updateStop(first.id, first.stops[0].id, String(owner.id), { status: 'arrived', version: 0 });
    assert.equal(arrived.version, duplicate.version);
    assert.equal(+new Date(arrived.stops[0].arrivedAt), +new Date(duplicate.stops[0].arrivedAt));
    assert.equal((await service.get(String(plan.id), String(member.id))).stops[0].status, 'pending');
    await assert.rejects(service.updateStop(first.id, first.stops[1].id, String(owner.id), { status: 'skipped', version: 0 }), error => error.code === 'VERSION_CONFLICT');
    await assert.rejects(service.finish(first.id, String(owner.id), { version: 1 }), error => error.code === 'UNRESOLVED_STOPS');

    const sharing = await service.setSharing(first.id, String(owner.id), { enabled: true });
    const sample = { latitude: 21.03, longitude: 105.8, accuracyMeters: 15, capturedAt: new Date().toISOString(), sharingVersion: sharing.sharingVersion };
    await service.updateLocation(first.id, String(owner.id), sample);
    assert.equal((await service.memberLocations(String(plan.id), String(member.id))).items[0].userId, String(owner.id));
    await assert.rejects(service.memberLocations(String(plan.id), String(outsider.id)), error => error.status === 403);
    await service.updateLocation(first.id, String(owner.id), { ...sample, latitude: 20, capturedAt: new Date(Date.now() - 1000).toISOString() });
    assert.equal((await service.memberLocations(String(plan.id), String(member.id))).items[0].latitude, 21.03);
    await service.setSharing(first.id, String(owner.id), { enabled: false });
    assert.equal((await service.memberLocations(String(plan.id), String(member.id))).items.length, 0);
    await assert.rejects(service.updateLocation(first.id, String(owner.id), sample), error => error.code === 'SHARING_DISABLED');
    await service.setSharing(second.id, String(member.id), { enabled: true });
    await db.$transaction(async tx => {
        await tx.itinerary_collaborators.deleteMany({ where: { itinerary_id: plan.id, user_id: member.id } });
        await reconcileExecutionMembers(tx, plan.id);
    });
    const cancelled = await db.trip_executions.findUnique({ where: { id: BigInt(second.id) } });
    assert.equal(cancelled.status, 'cancelled'); assert.equal(cancelled.active_user_id, null); assert.equal(cancelled.location_sharing, false);
    await assert.rejects(service.get(String(plan.id), String(member.id)), error => error.status === 403);
    const completed = await service.updateStop(first.id, first.stops[0].id, String(owner.id), { status: 'completed', version: 1 });
    const skipped = await service.updateStop(first.id, first.stops[1].id, String(owner.id), { status: 'skipped', version: completed.version });
    const finishShare = await service.setSharing(first.id, String(owner.id), { enabled: true });
    await service.updateLocation(first.id, String(owner.id), { ...sample, capturedAt: new Date().toISOString(), sharingVersion: finishShare.sharingVersion });
    const finished = await service.finish(first.id, String(owner.id), { version: skipped.version });
    assert.equal(finished.status, 'finished'); assert.equal(finished.locationSharing, false);
    assert.equal((await db.trip_executions.findUnique({ where: { id: BigInt(first.id) } })).latitude, null);
    assert.equal((await db.itineraries.findUnique({ where: { id: plan.id } })).status, 'draft');
    await service.start(String(another.id), String(owner.id));

    const session = await createAuthResponse(owner);
    const refreshResults = await Promise.allSettled([refreshToken(session.refreshToken), refreshToken(session.refreshToken)]);
    assert.equal(refreshResults.filter(result => result.status === 'fulfilled').length, 1);
    assert.equal(refreshResults.filter(result => result.status === 'rejected').length, 1);

    await db.user_messages.createMany({ data: Array.from({ length: 225 }, (_, index) => ({ sender_id: owner.id, receiver_id: member.id, content: String(index) })) });
    const latest = await getMessages(String(owner.id), String(member.id));
    assert.equal(latest.length, 100); assert.equal(latest.at(-1).content, '224');
    const page = await getMessages(String(owner.id), String(member.id), { limit: 100 });
    const older = await getMessages(String(owner.id), String(member.id), { limit: 100, cursor: page.nextCursor });
    assert.equal(new Set([...page.items, ...older.items].map(item => item.id)).size, 200);
    await db.itinerary_messages.createMany({ data: Array.from({ length: 225 }, (_, index) => ({ itinerary_id: plan.id, sender_id: owner.id, content: String(index) })) });
    assert.equal((await getTripGroupMessages(String(plan.id), String(owner.id))).at(-1).content, '224');
    const summaries = await service.summaries(String(owner.id), { limit: 1 });
    assert.equal(summaries.items.length, 1); assert.ok(summaries.nextCursor); assert.equal(summaries.items[0].items, undefined);

    const app = express(); app.use(express.json());
    app.use('/auth', authRoutes); app.use('/locations', locationRoutes); app.use('/executions', executionRoutes); app.use('/itineraries', itineraryRoutes);
    app.use('/weather', weatherRouter({ get: async () => ({ data: { temp: '25°C' } }) })); app.use(errorHandler);
    const server = app.listen(0, '127.0.0.1');
    await new Promise(resolve => server.once('listening', resolve));
    t.after(() => new Promise(resolve => server.close(resolve)));
    const base = `http://127.0.0.1:${server.address().port}`;
    const request = (method, path, token, body) => fetch(base + path, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, body: body ? JSON.stringify(body) : undefined });
    assert.equal((await request('POST', '/locations', null, {})).status, 401);
    assert.equal((await request('POST', '/locations/cache', session.token, {})).status, 403);
    assert.equal((await request('GET', '/locations/cache')).status, 405);
    assert.equal((await request('POST', '/auth/google', null, { credential: 'native' })).status, 403);
    assert.equal((await request('GET', '/weather?lat=21&lon=105')).status, 200);
    assert.equal((await request('GET', '/weather?lat=bad&lon=105')).status, 400);
    assert.equal((await request('GET', '/itineraries/summary', session.token)).status, 200);
    const running = await service.get(String(another.id), String(owner.id));
    const capability = await service.setSharing(running.id, String(owner.id), { enabled: true });
    assert.equal((await request('PUT', `/executions/${running.id}/location-upload`, capability.uploadToken, sample)).status, 200);
    assert.equal((await request('GET', '/itineraries/summary', capability.uploadToken)).status, 401);
    assert.equal((await request('PUT', `/executions/${first.id}/location-upload`, capability.uploadToken, sample)).status, 403);
    assert.equal((await request('POST', `/executions/${running.id}/location-stop`, capability.uploadToken, {})).status, 200);
    assert.equal((await request('PUT', `/executions/${running.id}/location-upload`, capability.uploadToken, sample)).status, 409);
    const activeShare = await service.setSharing(running.id, String(owner.id), { enabled: true });
    await service.stopUpload(running.id, String(owner.id), capability.sharingVersion);
    assert.equal((await service.get(String(another.id), String(owner.id))).sharingVersion, activeShare.sharingVersion);
    assert.equal((await service.get(String(another.id), String(owner.id))).locationSharing, true);
    await db.trip_executions.update({ where: { id: BigInt(running.id) }, data: { latitude: 21, longitude: 105, captured_at: new Date(Date.now() - 86400001) } });
    await service.purgeLocations();
    assert.equal((await db.trip_executions.findUnique({ where: { id: BigInt(running.id) } })).latitude, null);
    const logoutSession = await createAuthResponse(owner);
    await logout(logoutSession.refreshToken);
    assert.equal((await service.get(String(another.id), String(owner.id))).locationSharing, false);
    assert.equal((await request('PUT', `/executions/${running.id}/location-upload`, activeShare.uploadToken, sample)).status, 409);
});
